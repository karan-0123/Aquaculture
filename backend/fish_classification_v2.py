"""## 9. Fish Species Prediction"""

def build_features(ph, temperature, turbidity):
    """Compute all 16 features from 3 raw sensor readings."""
    DO      = float(np.clip(8 - 0.1*temperature - 0.05*turbidity, 3, 8))
    ammonia = float(np.clip(0.02*turbidity + 0.005*temperature,   0.01, 0.1))
    nitrite = float(np.clip(ammonia * 0.8,                         0.01, 0.05))
    BOD     = float(np.clip(5 - DO*0.5,                            1, 6))
    return pd.DataFrame([{
        'ph': ph, 'temperature': temperature, 'turbidity': turbidity,
        'DO': DO,
        # 'ammonia': ammonia,
        # 'nitrite': nitrite,
        'BOD': BOD,
        'ph_sq':       ph**2,
        'temp_sq':     temperature**2,
        'turb_sq':     turbidity**2,
        'ph_temp':     ph * temperature,
        'ph_turb':     ph * turbidity,
        'temp_turb':   temperature * turbidity,
        # 'DO_ph':       DO * ph,
        # 'DO_temp':     DO * temperature,
        # 'ammonia_BOD': ammonia * BOD,
    }])[FEATURES]


def predict_fish(ph, temperature, turbidity):
    """
    Predict which fish species can survive in given water conditions.

    Parameters
    ----------
    ph          : float  — pH of the pond water
    temperature : float  — water temperature in °C
    turbidity   : float  — turbidity in NTU

    Returns
    -------
    Prints the predicted fish species.
    """
    X_input = build_features(ph, temperature, turbidity)
    species = le.classes_[best_model.predict(X_input)[0]]
    print(f"pH: {ph}  |  Temperature: {temperature}°C  |  Turbidity: {turbidity} NTU")
    print(f"Predicted Fish Species: {species}")

