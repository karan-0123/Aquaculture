# Step 2: Augment with IoT sensor-realistic Gaussian noise
# Noise based on actual sensor datasheets:
#   pH sensor       : ±0.05 accuracy
#   DS18B20 temp    : ±0.30 °C
#   Turbidity sensor: ±0.15 NTU

TARGET_PER_CLASS = 400
PH_NOISE   = 0.05
TEMP_NOISE = 0.30
TURB_NOISE = 0.15

frames = []
for fish, grp in df_unique.groupby('fish'):
    frames.append(grp)
    need = TARGET_PER_CLASS - len(grp)
    rows = []
    for i in range(need):
        base = grp.sample(1, replace=True, random_state=i).iloc[0]
        rows.append({
            'ph':          round(float(np.clip(base['ph']          + np.random.normal(0, PH_NOISE),   5.0, 9.5)),  2),
            'temperature': round(float(np.clip(base['temperature'] + np.random.normal(0, TEMP_NOISE), 4.0, 36.0)), 2),
            'turbidity':   round(float(np.clip(base['turbidity']   + np.random.normal(0, TURB_NOISE), 1.0, 16.0)), 2),
            'fish': fish
        })
    frames.append(pd.DataFrame(rows))

df = pd.concat(frames, ignore_index=True).sample(frac=1, random_state=42).reset_index(drop=True)
print(f'Augmented dataset: {df.shape}')
print(f'Class distribution:\n{df["fish"].value_counts()}')
